# gen_texts.py <folder with the lockit files FFX_<lang>.bin, FFX2_<lang>.bin> > f60_texts.h
# The Framerate row's texts per game language, checked against the glyphs the game's own texts use, and written
# as a C table with \x escapes (the source stays ASCII).
import sys, os
S = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
LANGS = ['us', 'de', 'fr', 'it', 'sp', 'jp', 'kr', 'ch']
LABEL = {
    'us': 'Frame Rate', 'de': 'Framerate', 'fr': 'Fr\xe9quence d\'images', 'it': 'Frequenza fotogrammi',
    'sp': 'Fotogramas por segundo', 'jp': '\u30d5\u30ec\u30fc\u30e0\u30ec\u30fc\u30c8', 'kr': '\ud504\ub808\uc784 \ub808\uc774\ud2b8',
    'ch': 'FPS',
}
HELP = {
    'us': 'Set the frame rate. 30 fps is the original; 60 fps and more are drawn by the 60 fps patch. Takes effect at once.',
    'de': 'Bildrate einstellen. 30 fps ist das Original, ab 60 fps zeichnet der 60-fps-Patch. Wirkt sofort.',
    'fr': 'R\xe9gler la fr\xe9quence d\'images. 30 fps correspond \xe0 l\'original, 60 fps et plus au patch 60 fps. Effet imm\xe9diat.',
    'it': 'Imposta la frequenza dei fotogrammi. 30 fps \xe8 l\'originale, da 60 fps in su la patch 60 fps. Effetto immediato.',
    'sp': 'Establece los fotogramas por segundo. 30 fps es el original; 60 fps o m\xe1s, el parche de 60 fps. Efecto inmediato.',
    'jp': '\u30d5\u30ec\u30fc\u30e0\u30ec\u30fc\u30c8\u3092\u8a2d\u5b9a\u3057\u307e\u3059\u300230 fps\u306f\u30aa\u30ea\u30b8\u30ca\u30eb\u300160 fps\u306f60 fps\u30d1\u30c3\u30c1\u3067\u3059\u3002',
    'kr': '\ud504\ub808\uc784 \ub808\uc774\ud2b8 \uc124\uc815. 30 fps\ub294 \uc6d0\ubcf8, 60 fps\ub294 60 fps \ubaa8\ub4dc\uc785\ub2c8\ub2e4.',
    'ch': '\u8a2d\u5b9aFPS\u300230 FPS\u70ba\u539f\u59cb\u6a21\u5f0f\uff0c60 FPS\u70ba60 FPS\u6a21\u5f0f\u3002',
}
seen = {}
for l in LANGS:
    t = ''
    for g in ('FFX', 'FFX2'): t += open(os.path.join(S, '%s_%s.bin' % (g, l)), 'rb').read().decode('utf-8', 'replace')
    seen[l] = set(t)
bad = False
for l in LANGS:
    miss = sorted({c for c in LABEL[l] + HELP[l] if ord(c) > 127 and c not in seen[l]})
    if miss: bad = True; print('%s: not in the game texts: %s' % (l, ' '.join('U+%04X' % ord(c) for c in miss)))
if bad: sys.exit(1)
def c(s): return '"' + ''.join(ch if 32 <= ord(ch) < 127 and ch not in '"\\?' else ''.join('\\x%02x' % b for b in ch.encode('utf-8')) for ch in s) + '"'
# "\x.." followed by a hex digit would continue the escape: split the literal there
def lit(s):
    out = c(s)
    import re
    return re.sub(r'(\\x[0-9a-f]{2})(?=[0-9A-Fa-f])', r'\1""', out)
print('// generated by texts.py: the Framerate row in the game languages (UTF-8), order us de fr it sp jp kr ch')
print('static const char *const k_label[8] = {'); [print('    %s,' % lit(LABEL[l])) for l in LANGS]; print('};')
print('static const char *const k_help[8] = {'); [print('    %s,' % lit(HELP[l])) for l in LANGS]; print('};')
print('// the game\'s own "Texture Quality" label (FFX lockit line 585, FFX-2 1325) per language: tells which language the game shows')
print('static const char *const k_probe[8] = {')
for l in LANGS:
    a = open(os.path.join(S, 'FFX_%s.bin' % l), 'rb').read().decode('utf-8', 'replace').split('\r\n')[585]
    b = open(os.path.join(S, 'FFX2_%s.bin' % l), 'rb').read().decode('utf-8', 'replace').split('\r\n')[1325]
    assert a == b, (l, a, b)
    print('    %s,' % lit(a))
print('};')
