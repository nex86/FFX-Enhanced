#!/usr/bin/env python3
# gen_dbghelp.py - writes the dbghelp.dll forwarding layer of the optional DLL build (docs\FPS60_EXE.md section 12):
#   dll\dbghelp.def        exports: every name of the 32 bit system dbghelp.dll (the list of the FFX-60fps mod's loader,
#                          fps60\src\src\loader\forwards.cpp, 249 names) plus MiniDumpWriteDump, each bound to a stub
#   dll\dbghelp_fwd.S      one stub per export: jmp through f60_dbghelp_real[i] (no own code, no signature needed)
#   dll\f60_dbghelp.cpp    f60_dbghelp_init: loads <system dir>\dbghelp.dll by its full path and fills f60_dbghelp_real
# The forwards are resolved at run time instead of PE forwarders to "C:\Windows\System32\dbghelp.X": that keeps the DLL
# independent of the Windows folder's drive and name (Wine prefixes, SysWOW64 redirection).
#   python gen_dbghelp.py
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, '..', 'fps60', 'src', 'src', 'loader', 'forwards.cpp'))
OUT = os.path.join(HERE, 'dll')

def main():
    names = re.findall(r'/export:([A-Za-z0-9_]+)=', open(SRC, encoding='ascii').read())
    if 'MiniDumpWriteDump' not in names: names.append('MiniDumpWriteDump')
    names = sorted(set(names))
    os.makedirs(OUT, exist_ok=True)
    nl = '\r\n'
    head = ['; generated by gen_dbghelp.py - do not edit', 'LIBRARY dbghelp', 'EXPORTS']
    open(os.path.join(OUT, 'dbghelp.def'), 'w', newline='').write(nl.join(head + ['    %s=f60fwd_%s' % (n, n) for n in names]) + nl)
    s = ['/* generated by gen_dbghelp.py - do not edit: one jump per dbghelp export, through f60_dbghelp_real[i] */', '.text']
    for i, n in enumerate(names):
        s += ['.globl _f60fwd_%s' % n, '_f60fwd_%s:' % n, '    jmp *(_f60_dbghelp_real+%d)' % (4 * i)]
    open(os.path.join(OUT, 'dbghelp_fwd.S'), 'w', newline='').write(nl.join(s) + nl)
    c = ['// generated by gen_dbghelp.py - do not edit',
         '// The forwarding layer of dbghelp.dll: every export jumps through f60_dbghelp_real[i] (dbghelp_fwd.S). The table is',
         '// filled from the system dbghelp.dll, loaded by its full path. A name the system DLL lacks (Wine implements fewer)',
         '// points at f60_dbghelp_missing, which fails with ERROR_PROC_NOT_FOUND.',
         '#include <windows.h>',
         '#define F60_DBGHELP_N %d' % len(names),
         'extern "C" { void *f60_dbghelp_real[F60_DBGHELP_N]; int f60_dbghelp_resolved = -1; }',
         'static const char *const names[F60_DBGHELP_N] = {']
    for k in range(0, len(names), 6): c.append('    ' + ' '.join('"%s",' % n for n in names[k:k + 6]))
    c += ['};',
          'static int WINAPI f60_dbghelp_missing() { SetLastError(ERROR_PROC_NOT_FOUND); return 0; }',
          'extern "C" void f60_dbghelp_init(HINSTANCE self) {',
          '    wchar_t p[MAX_PATH + 16]; UINT n = GetSystemDirectoryW(p, MAX_PATH);',
          '    HMODULE m = 0;',
          '    if (n > 0 && n < MAX_PATH) { lstrcatW(p, L"\\\\dbghelp.dll"); m = LoadLibraryW(p); }',
          '    if (m == (HMODULE)self) m = 0;                       // never forward to this DLL itself',
          '    int ok = 0;',
          '    for (int i = 0; i < F60_DBGHELP_N; i++) {',
          '        void *f = m ? (void *)GetProcAddress(m, names[i]) : 0;',
          '        if (f) ok++; else f = (void *)&f60_dbghelp_missing;',
          '        f60_dbghelp_real[i] = f;',
          '    }',
          '    f60_dbghelp_resolved = m ? ok : -1;',
          '}']
    open(os.path.join(OUT, 'f60_dbghelp.cpp'), 'w', newline='').write(nl.join(c) + nl)
    print('%d exports -> %s' % (len(names), OUT))

if __name__ == '__main__': main()
